import { EDITABLE, type EntityField } from '@donotdev/core';

// ============================================================================
// Field type → value generators
// ============================================================================

const GENERATORS: Record<string, (field: EntityField) => unknown> = {
  text: (f) => {
    const max = (f.validation as any)?.maxLength ?? 20;
    return `test_${f.name}_${Date.now().toString(36)}`.slice(0, max);
  },
  textarea: (f) => `Test ${f.name} content — generated by @donotdev/testing`,
  richtext: () => '<p>Test rich text content</p>',
  email: () => `test_${Date.now().toString(36)}@example.com`,
  url: () => 'https://example.com/test',
  password: () => 'Test1234!@#$',
  tel: () => '+33612345678',
  iban: () => 'FR7630006000011234567890189',

  number: (f) => {
    const min = (f.validation as any)?.min ?? 0;
    const max = (f.validation as any)?.max ?? 100;
    return Math.floor(min + (max - min) / 2);
  },
  range: (f) => GENERATORS.number!(f),
  rating: () => 3,
  year: (f) => {
    const min = (f.validation as any)?.min ?? 2000;
    const max = (f.validation as any)?.max ?? new Date().getFullYear();
    return Math.floor(min + (max - min) / 2);
  },

  price: () => ({
    amount: 9900,
    currency: 'EUR',
    vatIncluded: true,
    discountPercent: 0,
  }),
  currency: (f) => {
    const min = (f.validation as any)?.min ?? 0;
    const max = (f.validation as any)?.max ?? 10000;
    return Math.floor(min + (max - min) / 2);
  },

  select: (f) => resolveFirstOption(f),
  radio: (f) => resolveFirstOption(f),
  combobox: (f) => resolveFirstOption(f) ?? `test_${f.name}`,
  multiselect: (f) => {
    const opt = resolveFirstOption(f);
    return opt ? [opt] : [];
  },

  boolean: () => true,
  checkbox: () => true,
  switch: (f) => {
    const checkedValue = (f.options as any)?.fieldSpecific?.checkedValue;
    return checkedValue !== undefined ? checkedValue : true;
  },

  date: () => new Date().toISOString().split('T')[0],
  'datetime-local': () => new Date().toISOString().slice(0, 16),
  time: () => '12:00',
  month: () => `${new Date().getFullYear()}-01`,
  week: () => `${new Date().getFullYear()}-W01`,
  timestamp: () => new Date().toISOString(),

  // File/image types — return null (handled separately by the test runner)
  image: () => null,
  images: () => [],
  file: () => null,
  files: () => [],
  document: () => null,
  documents: () => [],
  avatar: () => null,

  address: () => ({
    formatted_address: '1 rue de Rivoli, 75001 Paris, France',
    latitude: 48.8606,
    longitude: 2.3376,
  }),
  geopoint: () => ({ lat: 48.8566, lng: 2.3522 }),

  reference: () => '', // Can't generate a valid ref ID without context
  hidden: () => 'test_hidden_value',
  color: () => '#3B82F6',
  badge: () => 'test',
  map: () => ({ key1: 'value1' }),
  array: () => [],
  'field-array': () => [],
  duration: () => 3600,
  gdprConsent: () => true,
};

// ============================================================================
// Helpers
// ============================================================================

function resolveFirstOption(field: EntityField): string | undefined {
  const opts = (field.validation as any)?.options;
  if (!opts) return undefined;
  const resolved = typeof opts === 'function' ? opts({}) : opts;
  return resolved?.[0]?.value;
}

/**
 * Returns true if a field should be included in a create payload.
 * Skips auto-generated base fields, hidden, computed, and generated fields.
 */
function isWritableField(field: EntityField): boolean {
  // Skip base technical fields (auto-populated by framework/DB)
  const BASE_FIELDS = new Set([
    'id',
    'createdAt',
    'updatedAt',
    'createdById',
    'updatedById',
    'status',
  ]);
  if (BASE_FIELDS.has(field.name)) return false;

  // Skip non-writable editability modes
  if (
    field.editable === EDITABLE.GENERATED ||
    field.editable === EDITABLE.COMPUTED
  )
    return false;
  if (field.editable === false) return false;
  if (field.visibility === 'hidden') return false;

  return true;
}

/**
 * Returns true if the field holds a file/image that needs upload
 */
export function isFileField(field: EntityField): boolean {
  return [
    'image',
    'images',
    'file',
    'files',
    'document',
    'documents',
    'avatar',
  ].includes(field.type);
}

/**
 * Returns true if the field is a multi-file field
 */
export function isMultiFileField(field: EntityField): boolean {
  return ['images', 'files', 'documents'].includes(field.type);
}

// ============================================================================
// Public API
// ============================================================================

/**
 * Generate a test payload for an entity.
 * Returns only writable, non-file fields. File fields are handled separately.
 *
 * @param fields - Entity field definitions (entity.fields)
 * @param overrides - Partial payload to merge (takes precedence)
 */
export function generatePayload(
  fields: Record<string, EntityField>,
  overrides?: Record<string, unknown>
): Record<string, unknown> {
  const payload: Record<string, unknown> = {};

  for (const [key, field] of Object.entries(fields)) {
    if (!isWritableField(field)) continue;

    // Skip file fields — they're tested separately via storage
    if (isFileField(field)) continue;

    // Use override if provided
    if (overrides && key in overrides) {
      payload[key] = overrides[key];
      continue;
    }

    // Skip optional fields with no generator or that return empty
    const generator = GENERATORS[field.type];
    if (!generator) {
      // Unknown/custom type — skip unless required
      if ((field.validation as any)?.required) {
        payload[key] = `test_${field.type}_${key}`;
      }
      continue;
    }

    const value = generator(field);

    // Only include required fields + fields with non-null generated values
    if ((field.validation as any)?.required || value !== null) {
      payload[key] = value;
    }
  }

  // Merge remaining overrides (may include fields not in entity — e.g. scope fields)
  if (overrides) {
    for (const [key, value] of Object.entries(overrides)) {
      if (!(key in payload)) {
        payload[key] = value;
      }
    }
  }

  return payload;
}

/**
 * Extract file fields from entity definition
 */
export function getFileFields(
  fields: Record<string, EntityField>
): EntityField[] {
  return Object.values(fields).filter(
    (f) => isWritableField(f) && isFileField(f)
  );
}
